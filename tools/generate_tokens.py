"""Generate equivalent native tokens. Run --check in CI to reject drift."""
import json
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parents[1]
t = json.loads((root / 'design/tokens.json').read_text())
cs = ['// Generated by tools/generate_tokens.py. Do not edit.', 'namespace Synqora.Design;', 'public static class Tokens', '{']
kt = ['// Generated by tools/generate_tokens.py. Do not edit.', 'package com.synqora.design', 'import androidx.compose.ui.graphics.Color', 'object Tokens {']
for theme, colors in t['themes'].items():
    cs += [f'    public static readonly System.Collections.Generic.Dictionary<string, string> {theme.title()} = new()', '    {']
    kt += [f'    val {theme} = mapOf(']
    for name, value in colors.items():
        cs += [f'        ["{name}"] = "{value}",']
        kt += [f'        "{name}" to Color(0xFF{value[1:]}),']
    cs += ['    };']
    kt += ['    )']
for group in ['motion', 'radius']:
    for name, value in t[group].items():
        key = group.title() + name.title()
        cs += [f'    public const int {key} = {value};']
        kt += [f'    const val {key} = {value}']
cs += ['    public static readonly System.Collections.Generic.Dictionary<string, (double Opacity, int Radius, int Elevation)> Materials = new()', '    {']
kt += ['    data class Material(val opacity: Float, val radius: Int, val elevation: Int)', '    val materials = mapOf(']
for name, mat in t['materials'].items():
    cs += [f'        ["{name}"] = ({mat["opacity"]}, {mat["radius"]}, {mat["elevation"]}),']
    kt += [f'        "{name}" to Material({mat["opacity"]}f, {mat["radius"]}, {mat["elevation"]}),']
cs += ['    };', '}']
kt += ['    )', '}']
outputs = {'windows/Synqora/Design/Tokens.g.cs': '\n'.join(cs) + '\n', 'android/app/src/main/java/com/synqora/design/Tokens.kt': '\n'.join(kt) + '\n'}
for path, content in outputs.items():
    file = root / path
    if '--check' in sys.argv:
        if not file.exists() or file.read_text() != content:
            raise SystemExit(f'Token drift: {path}')
    else:
        file.parent.mkdir(parents=True, exist_ok=True)
        file.write_text(content)
print('Native design tokens are synchronized.')
